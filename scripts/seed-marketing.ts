/**
 * زرع الصفحات التسويقية — قابلة للاستدعاء من seed.ts أو مباشرة
 * آمن للتشغيل المتكرر: upsert ولا يمس أي بيانات أخرى
 */
export async function seedMarketing(): Promise<void> {
  console.log("⏳ جاري زرع الصفحات التسويقية...");

  for (const p of pages) {
    await db.marketingPage.upsert({
      where: { slug: p.slug },
      create: {
        slug: p.slug,
        title: p.title,
        subtitle: p.subtitle ?? null,
        kind: p.kind,
        status: "published",
        showInNav: true,
        navLabel: p.navLabel ?? null,
        order: p.order,
        heroBadge: p.heroBadge ?? null,
        heroTitle: p.heroTitle ?? null,
        heroSubtitle: p.heroSubtitle ?? null,
        ctaLabel: p.ctaLabel ?? null,
        sections: JSON.stringify(p.sections),
      },
      update: {
        title: p.title,
        subtitle: p.subtitle ?? null,
        kind: p.kind,
        navLabel: p.navLabel ?? null,
        order: p.order,
        heroBadge: p.heroBadge ?? null,
        heroTitle: p.heroTitle ?? null,
        heroSubtitle: p.heroSubtitle ?? null,
        ctaLabel: p.ctaLabel ?? null,
        sections: JSON.stringify(p.sections),
      },
    });
    console.log(`   ✓ ${p.slug} — ${p.navLabel ?? p.title}`);
  }

  const total = await db.marketingPage.count();
  console.log(`✅ الصفحات التسويقية جاهزة — الإجمالي: ${total}`);
}

// التشغيل المباشر فقط (وليس عند الاستيراد من seed.ts)
if (import.meta.main) {
  seedMarketing()
    .catch((e) => {
      console.error(e);
      process.exit(1);
    })
    .finally(async () => {
      await db.$disconnect();
    });
}
